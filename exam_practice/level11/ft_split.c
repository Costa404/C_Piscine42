
#include <stddef.h>
#include <stdlib.h>

char    **ft_split(char *str)

{
/*--------------------------------------------------------------------------------*/
    char **i;
    char **j;

    i = malloc(sizeof(char *) * 1024);
    if(!i)
        return NULL;

    j = i;
        
/*--------------------------------------------------------------------------------*/

    while(*str)
    {
        while(*str && *str <= 32)
            str++;

        if(*str > 32)
        {
/*--------------------------------------------------------------------------------*/

            *j = malloc(1024);
            if(!*j)
                return NULL;
            
            char *k = *j;

/*--------------------------------------------------------------------------------*/

            while(*str && *str > 32)
            {
                *k = *str;
                k++;
                str++;
            }
            
            *k = '\0';
            j++;

        }
    }
/*--------------------------------------------------------------------------------*/
    *j = NULL;
    return i;
}
